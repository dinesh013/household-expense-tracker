import { useCallback, useEffect, useState } from 'react';
import { FunctionsFetchError, FunctionsHttpError, FunctionsRelayError } from '@supabase/supabase-js';
import { supabase } from '../lib/supabase';
import { errorText, must, rpc } from '../lib/api';
import { useApp } from '../lib/session';
import { dateTimeLabel, type YearMonth } from '../lib/format';
import type { AiInsight, InsightContent } from '../lib/types';

/** Matches ai_insight_daily_limit() in the database. */
export const AI_DAILY_LIMIT = 5;

/** Why the Edge Function said no, from its JSON body ({ code, message }). */
async function functionError(err: unknown): Promise<{ code: string; message: string }> {
  if (err instanceof FunctionsHttpError) {
    const res = err.context as Response;
    // 404: the function was never deployed. Same as "not switched on".
    if (res.status === 404) return { code: 'not_configured', message: '' };
    try {
      const body = await res.json();
      if (body && typeof body.message === 'string') return { code: String(body.code ?? ''), message: body.message };
    } catch { /* fall through */ }
    return { code: '', message: 'AI Insight failed. Try again in a minute.' };
  }
  if (err instanceof FunctionsFetchError || err instanceof FunctionsRelayError) {
    return { code: '', message: "Couldn't reach AI Insight. Check your connection, or ask the Owner whether it has been set up." };
  }
  return { code: '', message: errorText(err) };
}

/**
 * "AI Insight": the most overspent category this month, 2–3 tips, and a light-hearted comparison with
 * a typical Velachery household. Generated by the ai-insight Edge Function; the latest one is shared.
 */
export function AiInsightCard({ ym }: { ym: YearMonth }) {
  const { household, nameOf } = useApp();
  const [insight, setInsight] = useState<AiInsight | null>(null);
  const [used, setUsed] = useState<number | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [off, setOff] = useState(false);
  const hid = household!.id;

  const load = useCallback(async () => {
    const [rows, n] = await Promise.all([
      must(supabase.from('ai_insights').select('id, year, month, content, created_by, created_at')
        .eq('household_id', hid).eq('year', ym.year).eq('month', ym.month).eq('status', 'done')
        .order('created_at', { ascending: false }).limit(1)),
      rpc<number>('ai_insights_used_today', { p_household: hid }),
    ]);
    setInsight((rows as AiInsight[])[0] ?? null);
    setUsed(n);
  }, [hid, ym.year, ym.month]);

  useEffect(() => {
    setInsight(null);
    setError(null);
    load().catch((e) => setError(errorText(e)));
  }, [load]);

  async function generate() {
    setBusy(true);
    setError(null);
    try {
      const { error: err } = await supabase.functions.invoke('ai-insight', { body: { household_id: hid, year: ym.year, month: ym.month } });
      if (err) {
        const f = await functionError(err);
        if (f.code === 'not_configured') setOff(true);
        else setError(f.message);
      }
      await load();
    } catch (e) {
      setError(errorText(e));
    } finally {
      setBusy(false);
    }
  }

  const left = used === null ? null : Math.max(0, AI_DAILY_LIMIT - used);
  const c: InsightContent | undefined = insight?.content;

  return (
    <section className="card stack ai-card" aria-labelledby="ai-h" aria-busy={busy}>
      <div className="card-head">
        <h2 id="ai-h"><span aria-hidden="true">✨ </span>AI Insight</h2>
        {left !== null && <span className="tiny muted">{left} of {AI_DAILY_LIMIT} left today</span>}
      </div>

      {c ? (
        <div className="stack ai-body">
          <p className="ai-headline"><strong>{c.headline}</strong></p>
          <ul className="ai-tips">{c.tips.map((t) => <li key={t}>{t}</li>)}</ul>
          <p className="ai-funny"><span aria-hidden="true">😄 </span>{c.funny}</p>
          <p className="tiny muted">
            Compared with: {c.benchmark_note}
            {c.sources.length > 0 && <> · Sources: {c.sources.map((s, i) => (
              <span key={s.url}>{i > 0 && ', '}<a href={s.url} target="_blank" rel="noopener noreferrer">{s.title}</a></span>
            ))}</>}
          </p>
          <p className="tiny muted">Asked by {nameOf(insight!.created_by)} · {dateTimeLabel(insight!.created_at)}</p>
        </div>
      ) : !off && (
        <p className="small muted">Find the category you're overspending on, with quick tips and a comparison with typical Velachery homes.</p>
      )}

      {off && <div className="alert info">AI Insight isn't switched on yet. The Owner needs to add an Anthropic API key (see the README).</div>}
      {error && <div className="alert error" role="alert">{error}</div>}

      {!off && (
        <div className="row wrap">
          <button type="button" className="btn secondary" disabled={busy || left === 0} onClick={generate}>
            {busy ? 'Checking Chennai prices…' : c ? 'New insight' : 'Get AI Insight'}
          </button>
          {busy && <span className="tiny muted">This can take up to a minute.</span>}
          {left === 0 && !busy && <span className="tiny muted">Daily limit reached. Try again tomorrow.</span>}
        </div>
      )}
      <p className="tiny muted">Sends only this month's category totals and how many people share them (no names or notes) to Claude, Anthropic's AI.</p>
    </section>
  );
}
